"""Emit the pins-only manifest a candidate author receives, from the frozen corpus.

`corpus.yaml` is written for the ledger's authors and for a reader of a score. It pins the
sources, and it also carries the analysis that pinning produced: the silicon revision codes, the
edition-by-edition errata map, the renumbering worked example, the applicability convention, and
comments explaining what each trap is. Several of those are themselves scored — ENC28J60-REG-015
is the EREVID revision codes, and rows about edition renumbering are exactly what the map
pre-digests. Handing that file to a candidate author gives away answers and makes a paired
with/without-skill comparison meaningless, which is what happened in the first practice run.

This projection emits only what an author needs to fetch and verify the sources: the device, the
documents and their editions by hash, and the reference driver's pin. It is built from an explicit
allowlist, so a key added to the corpus later is absent from the author's manifest until someone
adds it here deliberately, and it is re-emitted rather than copied, so no comment survives.

    uv run --with pyyaml python3 author_manifest.py --output author-manifest.yaml
    uv run --with pyyaml python3 author_manifest.py --check author-manifest.yaml

Exit codes: 0 clean, 1 a check found drift, 3 unreadable inputs or an output collision;
argparse usage errors use 2.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

import ledger_check

HERE = Path(__file__).resolve().parent
SCHEMA = 'enc28j60-author-manifest-1'

# Top-level corpus keys an author may see. Everything absent from this tuple is analysis, a
# scoring convention, or a fact a ledger row scores: silicon_revisions (ENC28J60-REG-015),
# errata_map and renumbering (the edition traps), applicability_columns (how rows are judged).
CORPUS_KEYS = ('pilot', 'device', 'driver', 'documents')
DRIVER_KEYS = ('repo', 'tag', 'tag_object', 'commit', 'tagged', 'license', 'files')
FILE_KEYS = ('path', 'bytes', 'sha256', 'git_blob')
DOCUMENT_KEYS = ('id', 'title', 'url_pattern', 'editions', 'current')
# `accompanies` is printed on the errata's own cover; `gap` is this benchmark's reading of what
# that pairing implies, and a candidate is scored on reaching that reading itself.
EDITION_KEYS = ('rev', 'year', 'pages', 'bytes', 'sha256', 'accompanies')

NOTICE = (
    'Pins only. Fetch each document from its url_pattern with the edition letter, verify the '
    'sha256, and read it yourself. This manifest deliberately carries no analysis of the sources: '
    'no errata index, no revision codes, no reading of which editions pair with which.'
)


def project(corpus):
    """The author's view of the frozen corpus: pins, and nothing derived from reading them."""
    out = {'schema': SCHEMA, 'notice': NOTICE}
    for key in CORPUS_KEYS:
        if key not in corpus:
            continue
        value = corpus[key]
        if key == 'driver':
            out[key] = {k: v for k, v in value.items() if k in DRIVER_KEYS}
            out[key]['files'] = [{k: v for k, v in f.items() if k in FILE_KEYS}
                                 for f in value.get('files', [])]
        elif key == 'documents':
            out[key] = {
                name: dict({k: v for k, v in doc.items() if k in DOCUMENT_KEYS},
                           editions=[{k: v for k, v in ed.items() if k in EDITION_KEYS}
                                     for ed in doc.get('editions', [])])
                for name, doc in value.items()}
        else:
            out[key] = value
    return out


def render(manifest):
    import yaml
    header = ('# SPDX-FileCopyrightText: 2026 contributors\n'
              '# SPDX-License-Identifier: Apache-2.0\n'
              '#\n'
              '# Generated by author_manifest.py from the frozen corpus. Do not edit: regenerate.\n')
    return (header + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True,
                                    default_flow_style=False)).encode()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--corpus', type=Path, default=HERE / 'corpus.yaml')
    parser.add_argument('--output', type=Path, help='new file; never overwritten')
    parser.add_argument('--check', type=Path, help='compare an existing manifest with this corpus')
    try:
        args = parser.parse_args(argv)
        corpus = ledger_check.load_yaml(args.corpus)
        rendered = render(project(corpus))
        if args.check:
            current = args.check.read_bytes()
            if current == rendered:
                print(f'{args.check}: matches the frozen corpus')
                return 0
            print(f'{args.check}: does not match the projection of {args.corpus}; regenerate it',
                  file=sys.stderr)
            return 1
        if args.output:
            with args.output.open('xb') as f:
                f.write(rendered)
            print(f'{args.output}: written')
            return 0
        sys.stdout.buffer.write(rendered)
        return 0
    except FileExistsError:
        print(f'author_manifest: {args.output}: exists; write to a new path', file=sys.stderr)
        return 3
    except OSError as exc:
        print(f'author_manifest: {exc}', file=sys.stderr)
        return 3


if __name__ == '__main__':
    sys.exit(main())
